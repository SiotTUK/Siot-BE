package com.siot.backend.schedule.dto;

import com.siot.backend.schedule.domain.CalendarSchedule;
import io.swagger.v3.oas.annotations.media.Schema;

import java.time.LocalDate;
import java.time.OffsetDateTime;

@Schema(description = "관리자: 달력 공통 일정")
public record AdminScheduleResponse(
        @Schema(description = "일정 ID", example = "10") Long scheduleId,
        @Schema(description = "일정 종류", example = "TAX_CAR") String kind,
        @Schema(description = "연결된 항목 코드", nullable = true, example = "tax-car") String guideCode,
        @Schema(description = "시작일", example = "2027-06-16") LocalDate startsOn,
        @Schema(description = "마감일", nullable = true, example = "2027-06-30") LocalDate endsOn,
        @Schema(description = "대상 설명", nullable = true) String targetDescription,
        @Schema(description = "출처·납부 링크", nullable = true) String sourceUrl,
        @Schema(description = "달력·알림에 보이는지") boolean active,
        @Schema(description = "자동 생성된 일정인지 (등록한 관리자가 없음)") boolean autoGenerated,
        @Schema(description = "등록한 관리자 ID", nullable = true) Long createdBy,
        @Schema(description = "마지막으로 고친 관리자 ID", nullable = true) Long updatedBy,
        @Schema(description = "마지막 변경 시각") OffsetDateTime updatedAt
) {

    public static AdminScheduleResponse of(CalendarSchedule schedule, String guideCode) {
        return new AdminScheduleResponse(schedule.getId(), schedule.getKind(), guideCode, schedule.getStartsOn(),
                schedule.getEndsOn(), schedule.getTargetDescription(), schedule.getSourceUrl(), schedule.isActive(),
                schedule.getCreatedBy() == null, schedule.getCreatedBy(), schedule.getUpdatedBy(),
                schedule.getUpdatedAt());
    }
}
