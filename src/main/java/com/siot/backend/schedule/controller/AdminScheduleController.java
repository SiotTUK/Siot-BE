package com.siot.backend.schedule.controller;

import com.siot.backend.auth.security.MemberPrincipal;
import com.siot.backend.global.common.ApiResponse;
import com.siot.backend.global.config.openapi.ApiErrorCodes;
import com.siot.backend.global.exception.ErrorCode;
import com.siot.backend.schedule.dto.AdminScheduleRequest;
import com.siot.backend.schedule.dto.AdminScheduleResponse;
import com.siot.backend.schedule.dto.TaxScheduleGenerateResponse;
import com.siot.backend.schedule.service.AdminScheduleService;
import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.Parameter;
import io.swagger.v3.oas.annotations.tags.Tag;
import jakarta.validation.Valid;
import lombok.RequiredArgsConstructor;
import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.security.core.annotation.AuthenticationPrincipal;
import org.springframework.web.bind.annotation.*;

import java.util.List;

/** 관리자: 달력 공통 일정 (세금 일정 포함) */
@Tag(name = "9-6. 관리자: 달력 일정",
        description = "생활 달력의 공통 일정(세금 납부 기간 등) 조회·등록·수정과 세금 일정 자동 생성 (CAL-01~03, NTF-01). 관리자만")
@RestController
@RequestMapping("/api/admin/schedules")
@RequiredArgsConstructor
public class AdminScheduleController {

    private final AdminScheduleService adminScheduleService;

    @Operation(summary = "공통 일정 목록",
            description = "그해 시작하는 공통 일정을 꺼 둔 것까지 시작일 순으로. kind 를 주면 그 종류만 "
                    + "(세금은 연결 항목으로 같은 세금인 일정 포함). autoGenerated=true 는 자동 생성된 일정")
    @ApiErrorCodes(ErrorCode.INVALID_INPUT)
    @GetMapping
    public ResponseEntity<ApiResponse<List<AdminScheduleResponse>>> list(
            @Parameter(description = "연도 (2000~2100)", example = "2027") @RequestParam int year,
            @Parameter(description = "일정 종류 (TAX_CAR 등). 생략하면 전체") @RequestParam(required = false) String kind) {
        return ResponseEntity.ok(ApiResponse.of(adminScheduleService.list(year, kind)));
    }

    @Operation(summary = "공통 일정 등록",
            description = "연납 신청 기간, 기한 연장처럼 정기분 밖의 일정을 넣는다. kind 에 TAX 가 들어가면 세금 상세·세금 알림 대상")
    @ApiErrorCodes({ErrorCode.INVALID_INPUT, ErrorCode.GUIDE_NOT_FOUND})
    @PostMapping
    public ResponseEntity<ApiResponse<AdminScheduleResponse>> create(
            @AuthenticationPrincipal MemberPrincipal principal,
            @Valid @RequestBody AdminScheduleRequest request) {
        return ResponseEntity.status(HttpStatus.CREATED)
                .body(ApiResponse.of(adminScheduleService.create(principal.getId(), request)));
    }

    @Operation(summary = "공통 일정 수정",
            description = "모든 값을 덮어쓴다. 자동 생성된 일정도 고칠 수 있고, 고친 일정은 자동 생성이 다시 바꾸지 않는다. "
                    + "지우는 대신 active=false 로 끈다 (꺼 둔 회차는 자동 생성이 다시 만들지 않는다)")
    @ApiErrorCodes({ErrorCode.SCHEDULE_NOT_FOUND, ErrorCode.INVALID_INPUT, ErrorCode.GUIDE_NOT_FOUND})
    @PutMapping("/{scheduleId}")
    public ResponseEntity<ApiResponse<AdminScheduleResponse>> update(
            @AuthenticationPrincipal MemberPrincipal principal,
            @Parameter(description = "일정 ID") @PathVariable Long scheduleId,
            @Valid @RequestBody AdminScheduleRequest request) {
        return ResponseEntity.ok(ApiResponse.of(adminScheduleService.update(principal.getId(), scheduleId, request)));
    }

    @Operation(summary = "세금 일정 자동 생성 실행",
            description = "그해 정기분(자동차세 6·12월, 재산세 7·9월, 주민세 개인분 8월, 16일~말일) 중 없는 회차를 만든다. "
                    + "말일이 토·일·공휴일이면 다음 영업일이 마감 (지방세기본법 제24조). 이미 있는 회차는 그대로. "
                    + "서버는 올해 일정을 매일, 내년 일정을 12월부터 스스로 만든다. officialHolidays=false 면 공휴일 자료 없이 계산했으므로 마감일을 확인한다")
    @ApiErrorCodes(ErrorCode.INVALID_INPUT)
    @PostMapping("/taxes/generate")
    public ResponseEntity<ApiResponse<TaxScheduleGenerateResponse>> generateTaxSchedules(
            @Parameter(description = "연도 (2000~2100)", example = "2027") @RequestParam int year) {
        return ResponseEntity.ok(ApiResponse.of(adminScheduleService.generateTaxSchedules(year)));
    }
}
