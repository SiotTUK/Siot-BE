/**
 * 공통 세금 일정 자동 생성과 관리자 수정. 공휴일은 가짜 자료 (천문연 대신).
 * 연도는 서버가 스스로 만드는 올해·내년과 겹치지 않게 테스트마다 먼 해를 쓴다.
 */
@SpringBootTest
@AutoConfigureMockMvc
@Import(TestcontainersConfiguration.class)
class TaxScheduleIntegrationTest {

    @Autowired
    MockMvc mockMvc;
    @Autowired
    AppUserRepository users;
    @Autowired
    JdbcTemplate jdbcTemplate;

    @MockitoBean
    HolidaySource holidaySource;

    private MemberPrincipal admin;
    private MemberPrincipal member;

    @BeforeEach
    void setUp() {
        AppUser adminUser = AppUser.create(email(), "unused");
        adminUser.changeRole(Role.ADMIN);
        admin = MemberPrincipal.from(users.save(adminUser));
        member = MemberPrincipal.from(users.save(AppUser.create(email(), "unused")));
    }

    @Test
    void generatesRegularTaxSchedulesWithDeadlinesMovedPastHolidaysOnce() throws Exception {
        int year = 2031;
        // 2031-08-31 일요일 → 09-01 (가짜 공휴일) → 09-02 화요일
        given(holidaySource.holidays(anyInt())).willAnswer(inv -> {
            int y = inv.getArgument(0);
            return y == year ? Set.of(LocalDate.of(year, 1, 1), LocalDate.of(year, 9, 1)) : Set.of(LocalDate.of(y, 1, 1));
        });
        clear(year);

        generate(year)
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.data.officialHolidays").value(true))
                .andExpect(jsonPath("$.data.created[*].kind",
                        contains("TAX_CAR", "TAX_PROPERTY", "TAX_RESIDENT", "TAX_PROPERTY", "TAX_CAR")))
                .andExpect(jsonPath("$.data.created[*].guideCode",
                        contains("tax-car", "tax-property", "tax-resident", "tax-property", "tax-car")))
                .andExpect(jsonPath("$.data.created[*].startsOn",
                        contains("2031-06-16", "2031-07-16", "2031-08-16", "2031-09-16", "2031-12-16")))
                .andExpect(jsonPath("$.data.created[*].endsOn",
                        contains("2031-06-30", "2031-07-31", "2031-09-02", "2031-09-30", "2031-12-31")))
                .andExpect(jsonPath("$.data.created[*].autoGenerated", everyItem(is(true))));

        // 다시 돌려도 새로 만들지 않는다
        generate(year).andExpect(jsonPath("$.data.created", hasSize(0)));
        list(year, null).andExpect(jsonPath("$.data", hasSize(5)));

        // 만든 일정은 세금 상세·문의처로 바로 쓰인다
        Long june = jdbcTemplate.queryForObject(
                "SELECT schedule_id FROM calendar_schedule WHERE kind = 'TAX_CAR' AND starts_on = ?", Long.class,
                LocalDate.of(year, 6, 16));
        mockMvc.perform(get("/api/schedules/taxes/{id}", june).with(user(member)))
                .andExpect(jsonPath("$.data.contact").value("시흥시 시세관리과 031-310-2093"))
                .andExpect(jsonPath("$.data.endsOn").value("2031-06-30"));
    }

    @Test
    void adminEditsAndDeactivationSurviveRegeneration() throws Exception {
        int year = 2032;
        given(holidaySource.holidays(anyInt())).willAnswer(inv -> Set.of(LocalDate.of((int) inv.getArgument(0), 1, 1)));
        clear(year);
        generate(year).andExpect(jsonPath("$.data.created", hasSize(5)));
        Long june = id(year, "TAX_CAR", 6);
        Long resident = id(year, "TAX_RESIDENT", 8);

        // 임시공휴일·기한 연장: 마감일을 고친다
        save(put("/api/admin/schedules/{id}", june), """
                {"kind":"TAX_CAR","guideCode":"tax-car","startsOn":"2032-06-16","endsOn":"2032-07-05",
                 "sourceUrl":"https://www.wetax.go.kr"}""")
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.data.endsOn").value("2032-07-05"))
                .andExpect(jsonPath("$.data.autoGenerated").value(true))
                .andExpect(jsonPath("$.data.updatedBy").value(admin.getId()));
        // 지우는 대신 끈다
        save(put("/api/admin/schedules/{id}", resident), """
                {"kind":"TAX_RESIDENT","guideCode":"tax-resident","startsOn":"2032-08-16","endsOn":"2032-08-31",
                 "active":false}""")
                .andExpect(jsonPath("$.data.active").value(false));

        // 다시 생성해도 고친 마감일·꺼 둔 회차는 그대로
        generate(year).andExpect(jsonPath("$.data.created", hasSize(0)));
        list(year, "TAX_CAR")
                .andExpect(jsonPath("$.data[*].endsOn", contains("2032-07-05", "2032-12-31")));
        list(year, "TAX_RESIDENT")
                .andExpect(jsonPath("$.data[0].active").value(false));
        // 꺼 둔 일정은 사용자 세금 목록에 나오지 않는다
        mockMvc.perform(get("/api/schedules/taxes").param("kind", "TAX_RESIDENT").with(user(member)))
                .andExpect(jsonPath("$.data[?(@.scheduleId == " + resident + ")]", hasSize(0)));
    }

    @Test
    void adminCreatesExtraScheduleAndInputIsChecked() throws Exception {
        given(holidaySource.holidays(anyInt())).willAnswer(inv -> Set.of(LocalDate.of((int) inv.getArgument(0), 1, 1)));
        clear(2033);

        // 정기분 밖 일정 (자동차세 연납 신청)
        save(post("/api/admin/schedules"), """
                {"kind":"TAX_CAR_PREPAY","guideCode":"tax-car","startsOn":"2033-01-16","endsOn":"2033-01-31",
                 "targetDescription":"자동차세 연납 신청"}""")
                .andExpect(status().isCreated())
                .andExpect(jsonPath("$.data.kind").value("TAX_CAR_PREPAY"))
                .andExpect(jsonPath("$.data.active").value(true))
                .andExpect(jsonPath("$.data.autoGenerated").value(false))
                .andExpect(jsonPath("$.data.createdBy").value(admin.getId()));

        // 마감일이 시작일보다 빠름 / 없는 항목 / 잘못된 종류 / 없는 일정
        save(post("/api/admin/schedules"), """
                {"kind":"TAX_CAR","startsOn":"2033-06-30","endsOn":"2033-06-16"}""")
                .andExpect(status().isBadRequest()).andExpect(jsonPath("$.code").value("INVALID_INPUT"));
        save(post("/api/admin/schedules"), """
                {"kind":"TAX_CAR","guideCode":"no-such-guide","startsOn":"2033-06-16"}""")
                .andExpect(status().isNotFound()).andExpect(jsonPath("$.code").value("GUIDE_NOT_FOUND"));
        save(post("/api/admin/schedules"), """
                {"kind":"tax car","startsOn":"2033-06-16"}""")
                .andExpect(status().isBadRequest());
        save(put("/api/admin/schedules/{id}", 999_999_999L), """
                {"kind":"TAX_CAR","startsOn":"2033-06-16"}""")
                .andExpect(status().isNotFound()).andExpect(jsonPath("$.code").value("SCHEDULE_NOT_FOUND"));
        mockMvc.perform(post("/api/admin/schedules/taxes/generate").param("year", "1999").with(user(admin)).with(csrf()))
                .andExpect(status().isBadRequest());

        // 관리자만
        mockMvc.perform(get("/api/admin/schedules").param("year", "2033").with(user(member)))
                .andExpect(status().isForbidden());
        mockMvc.perform(post("/api/admin/schedules/taxes/generate").param("year", "2033").with(user(member)).with(csrf()))
                .andExpect(status().isForbidden());
    }

    @Test
    void reportsWhenDeadlinesWereComputedWithoutHolidayData() throws Exception {
        given(holidaySource.holidays(anyInt())).willThrow(new HolidaySource.HolidayUnavailableException("no key"));
        clear(2034);

        generate(2034)
                .andExpect(jsonPath("$.data.created", hasSize(5)))
                .andExpect(jsonPath("$.data.officialHolidays").value(false));
    }

    private ResultActions generate(int year) throws Exception {
        return mockMvc.perform(post("/api/admin/schedules/taxes/generate").param("year", String.valueOf(year))
                .with(user(admin)).with(csrf()));
    }

    private ResultActions list(int year, String kind) throws Exception {
        var request = get("/api/admin/schedules").param("year", String.valueOf(year)).with(user(admin));
        if (kind != null) {
            request.param("kind", kind);
        }
        return mockMvc.perform(request);
    }

    private ResultActions save(org.springframework.test.web.servlet.request.MockHttpServletRequestBuilder request,
                               String json) throws Exception {
        return mockMvc.perform(request.with(user(admin)).with(csrf())
                .contentType(MediaType.APPLICATION_JSON).content(json));
    }

    private Long id(int year, String kind, int month) {
        return jdbcTemplate.queryForObject("SELECT schedule_id FROM calendar_schedule WHERE kind = ? AND starts_on = ?",
                Long.class, kind, LocalDate.of(year, month, 16));
    }

    /** 다시 실행해도 같은 결과가 나오도록 그해 일정을 비운다 (알림이 가리키는 일정은 SET NULL) */
    private void clear(int year) {
        jdbcTemplate.update("DELETE FROM calendar_schedule WHERE starts_on BETWEEN ? AND ?",
                LocalDate.of(year, 1, 1), LocalDate.of(year, 12, 31));
    }

    private static String email() {
        return "tax" + ThreadLocalRandom.current().nextLong(1_000_000_000L, 9_999_999_999L) + "@example.com";
    }
}
